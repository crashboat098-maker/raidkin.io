const CHARS = ' ' + Object.keys(GLYPHS).join('');

/** Create the font once per game. Safe to call repeatedly. */
export function ensurePixelFont (scene: Scene): void
{
    if (scene.cache.bitmapFont.exists(PIXEL_FONT)) return;

    if (!scene.textures.exists(SHEET_KEY))
    {
        const texture = scene.textures.createCanvas(SHEET_KEY, CELL_WIDTH * CHARS.length, CELL_HEIGHT);
        if (!texture) return;
        const ctx = texture.getContext();

        [...CHARS].forEach((char, index) => {
            const glyph = GLYPHS[char];
            if (!glyph) return;
            const left = index * CELL_WIDTH;

            // Shadow first (offset 1px down-right), then the white letter on top.
            for (const [color, offset] of [['#000000', 1], ['#ffffff', 0]] as const)
            {
                ctx.fillStyle = color;
                glyph.forEach((row, y) => {
                    for (let x = 0; x < row.length; x++)
                    {
                        if (row[x] === '#') ctx.fillRect(left + x + offset, y + offset, 1, 1);
                    }
                });
            }
        });
        texture.refresh();
    }

    scene.cache.bitmapFont.add(PIXEL_FONT, GameObjects.RetroFont.Parse(scene, {
        image: SHEET_KEY,
        width: CELL_WIDTH,
        height: CELL_HEIGHT,
        chars: CHARS,
        charsPerRow: CHARS.length,
        'offset.x': 0,
        'offset.y': 0,
        'spacing.x': 0,
        'spacing.y': 0,
        lineSpacing: 0,
    }));
}
